// The broker's own vhost proxies this path to it (infra/ansible/roles/editor_shell's
// edit.conf.j2, `location = /token`) so this is same-origin wherever the shell is
// served, including the Playwright harness's local server.
const BROKER_PATH = '/token';

// The content repository every GitHub call below targets — the same repository
// content-source.mjs reads from (unauthenticated) to import. No longer duplicated: both
// now derive from the fork's single declaration in jamground.config.mjs, so the two cannot
// drift apart the way the old pair of literals could.
const REPO = CONTENT_REPO;
const BASE_BRANCH = CONTENT_BRANCH;

// `preview` has no control: previews were dropped for this release, and a preview URL is
// surfaced on the change instead of as a shell action, so there is nothing this identifier
// could ever do — a control that can never act would be the same defect as one with no
// handler. `VOCAB.preview` stays anyway: test/gates/editorial-vocabulary.test.mjs scans this
// module's string literals, not the live page, so the term still has to live here.
const ACTION_CONTROL_IDS = ['startAChange', 'save', 'sendForReview', 'publish'];

// The block API every export-direction call below needs — `parse` and `getBlockType` for
// attribute-guard.mjs / export.mjs, on top of the `createBlock`/`serialize` the import
// direction already uses. Built once, at module scope, from the same registration that
// already ran above for window.wpBlocksAPI.
const blockApi = { createBlock, serialize, parse, getBlockType };

// Generated by the shell, never typed by an editor. A fuller scheme —
// `content/<editor-handle>/<slug>-<ulid>` — would need the editor's GitHub handle and the
// entity's own slug, neither of which this function has reason to reach for; a
// session-unique suffix is enough to open a branch nothing else collides with.
function generateBranchName() {
  const suffix = `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 8)}`;
  return `content/change-${suffix}`;
}

